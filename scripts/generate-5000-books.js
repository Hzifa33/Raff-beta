function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function randInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function generate5000Dataset() {
  console.log('Generating 5,000 highly diverse benchmark books...');
  const books = [];
  const TOTAL = 5000;
  const now = new Date();

  // Create date helpers
  const makeIsoDate = (daysAgo) => {
    const d = new Date(now.getTime() - daysAgo * 24 * 60 * 60 * 1000);
    return d.toISOString();
  };

  let globalLoanCount = 0;

  for (let i = 1; i <= TOTAL; i++) {
    const cat = pick(CATEGORIES);
    const author = pick(cat.authors);
    const publisher = pick(PUBLISHERS);
    const shelf = pick(cat.shelves);

    // Varied volume distribution:
    // 75% single volume, 15% 2-4 volumes, 8% 5-10 volumes, 2% 12-30 volumes (encyclopedic compendiums)
    let volumes = 1;
    const vRoll = Math.random();
    if (vRoll > 0.98) {
      volumes = pick([12, 15, 16, 20, 24, 30]);
    } else if (vRoll > 0.90) {
      volumes = pick([5, 6, 7, 8, 10]);
    } else if (vRoll > 0.75) {
      volumes = pick([2, 3, 4]);
    }

    const copiesTotal = pick([1, 1, 1, 2, 2, 3, 4, 5, 8]);
    const baseTitle = pick(cat.titles);

    // Create unique titles by appending subtitle or edition descriptor when duplicates happen
    const titleSuffixes = [
      '',
      ' (دراسة وتحقيق)',
      ': قراءة معاصرة وتحليل نقدي',
      ' مع الفهارس العامة والشواهد',
      ' وشروحه العلمية المصاحبة',
      ' في ضوء المناهج الحديثة',
      ' وتطبيقاتها المعاصرة',
      ' مع ملحق النصوص والوثائق',
      ' المعتمد لطلاب العلم',
      ` (الجزء التكميلي ${randInt(1, 4)})`
    ];
    const suffix = (i > 100 && Math.random() > 0.5) ? pick(titleSuffixes) : '';
    const title = `${baseTitle}${suffix} #${i}`;

    const publishYear = String(randInt(1975, 2025));
    const price = Number((randInt(20, 60) * volumes + randInt(0, 95) / 100).toFixed(2));
    const refSeq = String(i).padStart(4, '0');
    const referenceNumber = `raf-${refSeq}`;
    const id = `book-v4-bench-${refSeq}`;

    const hasSeries = Math.random() > 0.75;
    const series = hasSeries ? pick(SERIES_NAMES) : '';
    const seriesOrder = hasSeries ? String(randInt(1, 40)) : '';

    // Keywords
    const bookKeywords = [
      ...cat.keywords.slice(0, randInt(2, 4)),
      author.split(' ')[0],
      cat.name.split(' ')[0]
    ];

    // Generate realistic loans on ~10% of books
    const loans = [];
    if (Math.random() < 0.12 && globalLoanCount < 500) {
      const isHistorical = Math.random() > 0.65;
      const borrower = pick(BORROWERS);
      const loanId = `loan-${id}-1`;

      if (isHistorical) {
        // Returned loan
        const borrowedDaysAgo = randInt(20, 90);
        const returnedDaysAgo = borrowedDaysAgo - randInt(5, 18);
        loans.push({
          id: loanId,
          borrowerName: borrower.name,
          contact: borrower.contact,
          borrowedAt: makeIsoDate(borrowedDaysAgo),
          dueDate: makeIsoDate(borrowedDaysAgo - 30),
          returnedAt: makeIsoDate(returnedDaysAgo),
          type: 'full',
          volumes: Array.from({ length: volumes }, (_, idx) => idx + 1),
          volumeReturns: {},
          renewedCount: 0,
          notes: 'تمت إعادة الكتاب بحالة سليمة.'
        });
      } else {
        // Active loan: could be normal, due soon, overdue, or partial volume return
        globalLoanCount++;
        const stateRoll = Math.random();
        let borrowedDaysAgo = 10;
        let dueDateDaysAgo = -20; // 20 days in future

        if (stateRoll < 0.25) {
          // Overdue
          borrowedDaysAgo = randInt(35, 65);
          dueDateDaysAgo = borrowedDaysAgo - 30; // Positive number of days overdue
        } else if (stateRoll < 0.45) {
          // Due soon (within 1 to 3 days)
          borrowedDaysAgo = 28;
          dueDateDaysAgo = -randInt(1, 3);
        }

        const isPartial = volumes > 1 && Math.random() > 0.5;
        const volumeReturns = {};
        if (isPartial) {
          // Return volume 1, keeping other volumes active
          volumeReturns['1'] = {
            returnedAt: makeIsoDate(randInt(1, 5)),
            notes: 'إرجاع المجلد الأول، وبقاء بقية المجلدات مع المستعير'
          };
        }

        loans.push({
          id: loanId,
          borrowerName: borrower.name,
          contact: borrower.contact,
          borrowedAt: makeIsoDate(borrowedDaysAgo),
          dueDate: makeIsoDate(-dueDateDaysAgo),
          returnedAt: null,
          type: isPartial ? 'partial' : 'full',
          volumes: Array.from({ length: volumes }, (_, idx) => idx + 1),
          volumeReturns,
          renewedCount: randInt(0, 2),
          notes: isPartial ? 'إعارة جزئية لبعض الأجزاء' : 'إعارة نشطة'
        });
      }
    }

    books.push({
      id,
      title,
      author,
      publisher,
      category: cat.name,
      referenceNumber,
      copiesTotal,
      volumes,
      price,
      publishYear,
      edition: pick(EDITIONS),
      series,
      seriesOrder,
      shelf,
      condition: pick(CONDITIONS),
      language: 'العربية',
      acquisition: pick(ACQUISITIONS),
      keywords: Array.from(new Set(bookKeywords)),
      notes: `فهرسة نموذجية لـ "${title}"، موقع الحفظ على رف ${shelf}.`,
      createdAt: makeIsoDate(randInt(1, 180)),
      updatedAt: makeIsoDate(randInt(0, 10)),
      archivedAt: null,
      loans
    });
  }

  const payload = {
    schemaVersion: 8,
    exportedAt: now.toISOString(),
    generator: 'RAFF 4.0.0 Benchmark & Import Suite',
    settings: {
      institutionName: 'مكتبة دار المعرفة المركزية النموذجية',
      loanDurationDays: 30,
      labelColumns: 4,
      labelSize: 'small',
      labelShowPrice: true,
      labelShowShelf: true,
      labelShowMicrotext: true,
      scannerGapMs: 35,
      scannerTerminator: 'Enter',
      soundEnabled: true,
      savedFilters: [
        {
          id: 'sf-bench-1',
          name: 'الموسوعات الكبرى متعددة المجلدات',
          query: 'تفسير',
          field: 'all',
          status: 'available',
          sort: 'newest'
        },
        {
          id: 'sf-bench-2',
          name: 'كتب التاريخ والحضارة',
          query: 'تاريخ',
          field: 'all',
          status: 'available',
          sort: 'newest'
        }
      ]
    },
    books
  };

  const outputPath = path.resolve(__dirname, '..', 'raff-import-5000-books.json');
  console.log(`Writing JSON to ${outputPath}...`);
  fs.writeFileSync(outputPath, JSON.stringify(payload, null, 2), 'utf-8');

  const stats = fs.statSync(outputPath);
  console.log(`✓ Successfully generated 5,000 books! File size: ${(stats.size / 1024 / 1024).toFixed(2)} MB`);
  console.log(`✓ Active loans included: ${globalLoanCount}`);
  return outputPath;
}

