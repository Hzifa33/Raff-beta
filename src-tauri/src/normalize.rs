pub fn sanitize_price(value: Option<f64>) -> Option<f64> {
    match value {
        Some(n) if n.is_finite() && n >= 0.0 => Some((n * 100.0).round() / 100.0),
        _ => None,
    }
}

pub fn sanitize_keywords(raw: &[String]) -> Vec<String> {
    let mut out = Vec::new();
    for item in raw {
        for part in item.split(|c| c == ',' || c == '،') {
            let trimmed = part.trim().to_string();
            if !trimmed.is_empty() && !out.contains(&trimmed) {
                out.push(trimmed);
            }
        }
    }
    out
}

pub fn sanitize_condition(value: &str) -> String {
    let trimmed = value.trim();
    if crate::models::COPY_CONDITIONS.contains(&trimmed) {
        trimmed.to_string()
    } else {
        "جيدة".to_string()
    }
}

pub fn new_uuid() -> String {
    use rand::RngCore;
    let mut b = [0u8; 16];
    rand::thread_rng().fill_bytes(&mut b);
    b[6] = (b[6] & 0x0f) | 0x40;
    b[8] = (b[8] & 0x3f) | 0x80;
    format!(
        "{:02x}{:02x}{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
        b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7],
        b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]
    )
}

