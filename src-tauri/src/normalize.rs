/// Normalizes reference numbers, Arabic search tokens, and security recovery answers
/// with 100% behavioral parity to RAFF 3.0.0.

/// Cleans only formatting noise that cannot be a meaningful part of a reference
/// number: surrounding whitespace, invisible direction/zero-width characters,
/// Unicode dash variants, and spaces around separators. It deliberately keeps
/// every digit. Therefore `raf-0001` and `raf-1001` remain different identifiers.
pub fn clean_reference_text(value: &str) -> String {
    let mut s = String::with_capacity(value.len());
    for ch in value.chars() {
        // Strip zero-width & directional formatting marks
        if matches!(
            ch,
            '\u{200B}'..='\u{200F}'
                | '\u{202A}'..='\u{202E}'
                | '\u{2060}'..='\u{2069}'
                | '\u{FEFF}'
        ) {
            continue;
        }
        // Normalize Unicode dashes to ASCII hyphen '-'
        if matches!(
            ch,
            '\u{2010}'..='\u{2015}' | '\u{2212}' | '\u{FE58}' | '\u{FE63}' | '\u{FF0D}'
        ) {
            s.push('-');
            continue;
        }
        // Convert Arabic-Indic digits ٠-٩
        if ('\u{0660}'..='\u{0669}').contains(&ch) {
            let digit = (ch as u32) - 0x0660;
            s.push(char::from_digit(digit, 10).unwrap_or(ch));
            continue;
        }
        // Convert Eastern Arabic-Indic digits ۰-۹
        if ('\u{06F0}'..='\u{06F9}').contains(&ch) {
            let digit = (ch as u32) - 0x06F0;
            s.push(char::from_digit(digit, 10).unwrap_or(ch));
            continue;
        }
        s.push(ch);
    }

    // Collapse whitespace and spaces around hyphens
    let collapsed_ws: String = s.split_whitespace().collect::<Vec<_>>().join(" ");
    let parts: Vec<&str> = collapsed_ws.split('-').map(|p| p.trim()).collect();
    parts.join("-")
}

/// Canonical storage format for references generated by Raff. Custom schemes
/// are preserved (apart from harmless cleanup), while `RAF-1` becomes `raf-0001`.
pub fn normalize_reference_for_storage(value: &str) -> String {
    let cleaned = clean_reference_text(value);
    if let Some(digits) = parse_canonical_raf_digits(&cleaned) {
        let stripped = strip_leading_zeros(digits);
        return format!("raf-{:0>4}", stripped);
    }
    cleaned
}

/// Stable identity used everywhere uniqueness is checked. The comparison is on
/// the complete cleaned reference, never on a suffix or a partial match.
/// Formatting-equivalent canonical references (`raf-1` / `RAF – 0001`) collide,
/// while `raf-0001` / `raf-1001` do not.
pub fn reference_identity(value: &str) -> String {
    let cleaned = clean_reference_text(value);
    if cleaned.is_empty() {
        return String::new();
    }
    if let Some(digits) = parse_canonical_raf_digits(&cleaned) {
        let stripped = strip_leading_zeros(digits);
        return format!("raff:{}", stripped);
    }
    format!("custom:{}", cleaned.to_lowercase())
}

/// Returns the positive sequence number if `value` matches canonical `raf-<digits>`.
pub fn canonical_ref_seq(value: &str) -> Option<u64> {
    let cleaned = clean_reference_text(value);
    let digits = parse_canonical_raf_digits(&cleaned)?;
    let n: u64 = digits.parse().ok()?;
    if n > 0 {
        Some(n)
    } else {
        None
    }
}

fn parse_canonical_raf_digits(cleaned: &str) -> Option<&str> {
    if cleaned.len() < 5 {
        return None;
    }
    let prefix = &cleaned[..4];
    if !prefix.eq_ignore_ascii_case("raf-") {
        return None;
    }
    let rest = &cleaned[4..];
    if !rest.is_empty() && rest.chars().all(|c| c.is_ascii_digit()) {
        Some(rest)
    } else {
        None
    }
}

fn strip_leading_zeros(digits: &str) -> &str {
    let trimmed = digits.trim_start_matches('0');
    if trimmed.is_empty() {
        "0"
    } else {
        trimmed
    }
}

/// Normalizes Arabic text for forgiving search matching:
/// - strips diacritics (tashkeel) and the tatweel elongation mark
/// - unifies alef forms (أ إ آ ٱ) to ا
/// - unifies ta marbuta (ة) with ha (ه)
/// - unifies alef maqsura (ى) with ya (ي)
/// - unifies hamza-carrying waw/ya (ؤ ئ) with their base letter
pub fn normalize_arabic(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        if matches!(
            ch,
            '\u{064B}'..='\u{0652}' | '\u{0670}' | '\u{06D6}'..='\u{06ED}' | '\u{0640}'
        ) {
            continue;
        }
        let mapped = match ch {
            'أ' | 'إ' | 'آ' | 'ٱ' => 'ا',
            'ة' => 'ه',
            'ى' => 'ي',
            'ؤ' => 'و',
            'ئ' => 'ي',
            _ => ch,
        };
        for lower in mapped.to_lowercase() {
            out.push(lower);
        }
    }
    out.split_whitespace().collect::<Vec<_>>().join(" ")
}

